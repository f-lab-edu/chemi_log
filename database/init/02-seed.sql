-- 질문 Pool 시드. 120문항 (카테고리별 30문항)입니다.
-- 카테고리별 3개씩 무작위로 뽑으므로, 30개 중 3개면 뽑기가 실제로 무작위가 됩니다.
--
-- 질문 설계 기준
--   1. 정답이 없어야 합니다. 한쪽이 더 나은 사람으로 보이면 솔직하게 고르지 않고 정답을 고릅니다.
--      "가계부를 쓴다 / 안 쓴다" 는 탈락입니다. "좋은 밥 한 끼 / 만원짜리 다섯 번" 은 통과입니다.
--   2. 상황을 줍니다. "연락 스타일은?" 은 답이 뻔하지만
--      "카톡 답장이 6시간째 없다" 는 실제로 답이 나뉩니다.
--   3. 친구 사이에서 실제로 차이가 드러나는 것만 넣습니다. 혼자만의 습관은 대화 소재가 되지 않습니다.
--
-- 카테고리마다 성향 6개를 정하고 5문항씩 배치했습니다. 절 주석이 그 성향입니다.
-- **질문을 추가할 때 이 배분을 지켜야 합니다.** 카테고리 점수는 3문항으로 계산되므로,
-- 30개가 모두 같은 성향을 재면 어느 3개를 뽑아도 결과가 같아져 점수가 0점 아니면 100점으로 몰립니다.
-- 그러면 "가장 잘 맞는 카테고리" 콘텐츠가 의미를 잃습니다.

-- **이 줄을 지우지 마십시오. 지우면 아래 한글이 전부 깨진 채 저장됩니다.**
--
-- mysql:8.4 이미지 안의 mysql CLI 는 컨테이너에 LANG 이 없어 character_set_client 가
-- latin1 로 붙습니다. Docker 엔트리포인트가 그 클라이언트로 이 파일을 실행하므로,
-- UTF-8 한글 바이트가 latin1 문자로 해석돼 utf8mb4 컬럼에 이중 인코딩으로 들어갑니다.
--
-- **오류가 나지 않습니다.** VARCHAR 폭이 늘어난 길이를 담을 수 있어 1406 도 안 뜹니다.
-- 24자짜리 질문이 56자로 저장되고, 앱은 utf8mb4 로 붙으므로 깨진 글자를 그대로 내보냅니다.
--
-- 서버 옵션 --skip-character-set-client-handshake 로 막는 방법은 8.4 에서 못 씁니다.
-- unknown option 으로 서버가 기동하지 않습니다.
SET NAMES utf8mb4;

